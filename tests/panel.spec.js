test('administradores: criar, editar, desativar, persistir e proteger a própria conta', async ({ page }) => {
  await page.goto('./#admins');
  await expect(page.getByRole('heading', { name: 'Administradores', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Novo administrador', exact: true }).click();
  await page.getByLabel('Nome', { exact: true }).fill('Maria Admin');
  await page.getByLabel('E-mail de acesso').fill('maria@example.com');
  await page.getByLabel('Senha inicial').fill('MinhaSenha123');
  await page.getByRole('button', { name: 'Criar administrador' }).click();
  const row = page.locator('tbody tr').filter({ hasText: 'maria@example.com' });
  await expect(row).toContainText('Ativo');
  expect(await page.evaluate(() => localStorage.getItem('taxi-curuca-demo-v1'))).not.toContain('MinhaSenha123');
  await row.getByRole('button', { name: 'Editar' }).click();
  await expect(page.getByLabel('E-mail de acesso')).toHaveAttribute('readonly', '');
  await page.getByLabel('Nome', { exact: true }).fill('Maria Silva');
  await page.getByLabel('Acesso administrativo ativo').uncheck();
  await page.getByRole('button', { name: 'Salvar administrador' }).click();
  await page.reload();
  await expect(row).toContainText('Maria Silva');
  await expect(row).toContainText('Desativado');
  await page.locator('tbody tr').filter({ hasText: '(você)' }).getByRole('button', { name: 'Editar' }).click();
  await expect(page.getByLabel('Acesso administrativo ativo')).toBeDisabled();
});
