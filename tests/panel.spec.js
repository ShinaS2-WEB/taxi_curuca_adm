test('publicação em subdiretório: navegação, filtro, formulário, persistência e CSV', async ({ page }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('./');
  await expect(page.getByRole('heading', { name: 'Sua operação, em movimento.' })).toBeVisible();
  await page.locator('nav').getByRole('button', { name: 'Motoristas' }).click();
  await page.getByRole('textbox', { name: 'Buscar registros' }).fill('Marina');
  await expect(page.locator('.driver-card')).toHaveCount(1);
  await page.getByRole('button', { name: 'Gerenciar' }).click();
  await page.getByLabel('Vagas disponíveis').fill('7');
  await page.getByRole('button', { name: 'Salvar alterações' }).click();
  await expect(page.getByRole('alert')).toContainText('excedem');
  await page.getByLabel('Vagas disponíveis').fill('2');
  await page.getByLabel('Preço (R$)').fill('17.50');
  await page.getByRole('button', { name: 'Salvar alterações' }).click();
  await expect(page.locator('dialog')).toHaveCount(0);
  await expect(page.locator('.driver-card')).toContainText('17,50');
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Motoristas', exact: true })).toBeVisible();
  await expect(page.locator('.driver-card').first()).toContainText('2/6');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Exportar relatório' }).click();
  expect((await download).suggestedFilename()).toContain('taxi-curuca-drivers-');
  expect(errors).toEqual([]);
});
